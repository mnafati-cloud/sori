#!/usr/bin/env node
// Offline, deterministic publication. Generation is a separate, explicitly paid command.
import fs from 'node:fs/promises';
import path from 'node:path';
import vm from 'node:vm';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
import sharp from 'sharp';

export const dir = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(dir, '../..');
const inventoryFile = path.join(dir, 'inventory.json');
const manifestFile = path.join(root, 'docs/images-data.js');
const digest = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const readJSON = async file => JSON.parse(await fs.readFile(file, 'utf8'));
const writeJSON = (file, value) => fs.writeFile(file, JSON.stringify(value, null, 2) + '\n');
export async function promptFor(item) {
  return await fs.readFile(path.join(dir, 'style.md'), 'utf8') + '\n\nSubject:\n' + item.subject;
}
export async function loadInventory() {
  const data = await readJSON(inventoryFile);
  const ctx = {window:{}};
  vm.runInNewContext(await fs.readFile(path.join(root, 'docs/data.js'), 'utf8'), ctx);
  const seed = new Map(ctx.window.SEED.items.map(it => [it.id, it]));
  const seen = new Set();
  if(data.version !== 1 || data.style !== 'pinceau-blanc-v1') throw Error('Unknown inventory/style version');
  for(const it of data.items) {
    if(!/^[a-z0-9-]+$/.test(it.id) || seen.has(it.id)) throw Error('Invalid or duplicate id: '+it.id);
    seen.add(it.id);
    if(!seed.has(it.id) || seed.get(it.id).kr !== it.kr || seed.get(it.id).type !== 'word') throw Error('Seed mismatch: '+it.id);
    if(!['queued','approved','rejected'].includes(it.status) || !['question','support'].includes(it.usage)) throw Error('Invalid status/usage: '+it.id);
    if(!it.subject?.trim() || !it.sense?.trim()) throw Error('Missing subject/sense: '+it.id);
    if(!Array.isArray(it.accepted) || !Array.isArray(it.alternatives) ||
       [...it.accepted,...it.alternatives].some(x => typeof x !== 'string' || !x.trim())) throw Error('Invalid answers: '+it.id);
    if(it.usage === 'question' && !it.accepted.includes(it.kr)) throw Error('Canonical answer missing: '+it.id);
    if(it.accepted.some(x=>it.alternatives.includes(x))) throw Error('Conflicting answers: '+it.id);
  }
  return data;
}
export async function buildManifest(data) {
  const items = {};
  // The reference is shared by every image in this manifest; hash it once per build.
  const referenceSha256 = digest(await fs.readFile(path.join(dir, 'style-reference.png')));
  for(const it of data.items.filter(x=>x.status === 'approved').sort((a,b)=>a.id.localeCompare(b.id,'en'))) {
    if(!it.asset || !new RegExp('^'+it.id+'-[a-f0-9]{12}\\.webp$').test(it.asset)) throw Error('Unsafe asset name: '+it.id);
    const file = path.join(root, 'docs/images', it.asset), bytes = await fs.readFile(file);
    const meta = await sharp(bytes).metadata();
    await sharp(bytes).raw().toBuffer(); // actual decode, not just header inspection
    if(meta.format !== 'webp' || meta.width !== 512 || meta.height !== 512 || meta.pages > 1 || bytes.length > 80*1024) throw Error('Image dimensions/size invalid: '+it.id);
    if(digest(bytes) !== it.sha256 || !it.asset.includes(it.sha256.slice(0,12))) throw Error('Image hash mismatch: '+it.id);
    const review = await readJSON(path.join(dir, 'reviews', it.asset.replace('.webp','.json')));
    if(review.id !== it.id || review.sha256 !== it.sha256 || !review.reviewer || !review.note || !review.createdAt ||
       review.usage !== it.usage || review.sense !== it.sense || review.kr !== it.kr ||
       JSON.stringify(review.accepted) !== JSON.stringify(it.accepted) || JSON.stringify(review.alternatives) !== JSON.stringify(it.alternatives) ||
       review.prompt !== await promptFor(it) || review.referenceSha256 !== referenceSha256) throw Error('Missing or stale review: '+it.id);
    items[it.id] = {src:'./images/'+it.asset, usage:it.usage, alt:it.sense, accepted:it.accepted, alternatives:it.alternatives, bytes:bytes.length};
  }
  return '/* Generated by tools/images/pipeline.mjs build — do not edit. */\n'+
    '(function(root){"use strict";const data='+JSON.stringify({version:1,style:data.style,items})+';'+
    'if(typeof module!=="undefined"&&module.exports)module.exports=data;root.SORI_IMAGES_DATA=data;'+
    '})(typeof window!=="undefined"?window:globalThis);\n';
}
async function main() {
  const [command,...args] = process.argv.slice(2), data = await loadInventory();
  const item = id => { const it=data.items.find(x=>x.id===id); if(!it) throw Error('Unknown id: '+id); return it; };
  if(command === 'status') {
    for(const it of data.items) console.log(`${it.status.padEnd(8)} ${it.usage.padEnd(8)} ${it.id} ${it.kr} — ${it.sense}`);
  } else if(command === 'prompt') {
    console.log(await promptFor(item(args[0])));
  } else if(command === 'import') {
    const [id,source,provider,receiptFile] = args, it = item(id);
    if(!source || !provider) throw Error('import <id> <generated-file> <provider>');
    const bytes = await fs.readFile(source), meta = await sharp(bytes).metadata();
    if(!['png','webp','jpeg'].includes(meta.format) || meta.pages > 1 || meta.width !== meta.height || meta.width < 512) throw Error('Expected one square generated image, at least 512px');
    const out = path.join(dir, 'candidates', id+'-'+digest(bytes).slice(0,12));
    await fs.mkdir(out,{recursive:true});
    // Technical resize/encoding only; no cropping or repainting the generated subject.
    const encoded = await sharp(bytes).resize(512,512,{fit:'contain'}).flatten({background:'#000000'}).webp({quality:82,effort:6}).toBuffer();
    if(encoded.length > 80*1024) throw Error('Over 80 KiB: review compression before publication');
    await fs.writeFile(path.join(out,'image.webp'),encoded);
    let api;
    if(receiptFile){
      const receipt=await readJSON(receiptFile);
      if(receipt.id!==id || receipt.parameters?.prompt!==await promptFor(it) || receipt.referenceSha256!==digest(await fs.readFile(path.join(dir,'style-reference.png')))) throw Error('API receipt mismatch');
      api={model:receipt.model,endpoint:receipt.endpoint,parameters:receipt.parameters,usage:receipt.usage};
    }
    await writeJSON(path.join(out,'generation.json'),{
      id,provider,createdAt:new Date().toISOString(),sourceSha256:digest(bytes),sha256:digest(encoded),
      prompt:await promptFor(it),referenceSha256:digest(await fs.readFile(path.join(dir,'style-reference.png'))),
      encoding:{width:512,height:512,format:'webp',quality:82,sharp:sharp.versions.sharp},api
    });
    console.log(path.relative(root,out));
  } else if(command === 'approve') {
    const [id,candidate,reviewer,...notes] = args, it = item(id), note=notes.join(' ').trim();
    if(!candidate || !reviewer || !note) throw Error('approve <id> <candidate-directory> <reviewer> <visual/semantic-review-note>');
    const review = await readJSON(path.join(candidate,'generation.json'));
    const bytes = await fs.readFile(path.join(candidate,'image.webp'));
    if(review.id !== id || review.sha256 !== digest(bytes) || review.prompt !== await promptFor(it) ||
       review.referenceSha256 !== digest(await fs.readFile(path.join(dir,'style-reference.png')))) throw Error('Candidate does not match current recipe');
    const asset=id+'-'+review.sha256.slice(0,12)+'.webp';
    await fs.mkdir(path.join(root,'docs/images'),{recursive:true});
    await fs.mkdir(path.join(dir,'reviews'),{recursive:true});
    await fs.writeFile(path.join(root,'docs/images',asset),bytes);
    await writeJSON(path.join(dir,'reviews',asset.replace('.webp','.json')),{...review,reviewer,note,
      reviewedAt:new Date().toISOString(),kr:it.kr,sense:it.sense,usage:it.usage,accepted:it.accepted,alternatives:it.alternatives});
    it.status='approved';it.asset=asset;it.sha256=review.sha256;
    const output=await buildManifest(data);
    await writeJSON(inventoryFile,data);await fs.writeFile(manifestFile,output);
    console.log(`Approved ${id}: ${bytes.length} bytes`);
  } else if(command === 'build' || command === 'check') {
    const output=await buildManifest(data);
    if(command === 'build') await fs.writeFile(manifestFile,output);
    else if(await fs.readFile(manifestFile,'utf8') !== output) throw Error('Manifest is stale: run build');
    console.log(`${data.items.filter(x=>x.status==='approved').length} approved images; manifest ${command==='check'?'verified':'written'}`);
  } else throw Error('Commands: status | prompt <id> | import <id> <file> <provider> | approve <id> <dir> <reviewer> <note> | build | check');
}
if(process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main().catch(e=>{console.error(e.message);process.exitCode=1;});
